CREATE DATABASE IF NOT EXISTS includedlives_dev
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE includedlives_dev;

CREATE TABLE EMPRESA (
  CNPJ CHAR(14) NOT NULL,
  NOME_FANTASIA VARCHAR(150) NOT NULL,
  RAZAO_SOCIAL VARCHAR(150) NOT NULL,
  SENHA VARCHAR(255) NOT NULL,
  EMAIL VARCHAR(150) NOT NULL,
  RAMO VARCHAR(100),
  PORTE VARCHAR(30),
  RESPONSAVEL VARCHAR(150),
  CONTATO VARCHAR(20),
  CEP CHAR(8),
  LOGRADOURO VARCHAR(150),
  NUMERO VARCHAR(10),
  CIDADE VARCHAR(100),
  UF CHAR(2),
  COMPLEMENTO VARCHAR(100),
  BAIRRO VARCHAR(100),
  CONSTRAINT PK_EMPRESA PRIMARY KEY (CNPJ),
  CONSTRAINT UQ_EMPRESA_EMAIL UNIQUE (EMAIL)
) ENGINE=InnoDB;

CREATE TABLE VAGA (
  COD_VAGA BIGINT NOT NULL AUTO_INCREMENT,
  NOME VARCHAR(150),
  CNPJ CHAR(14),
  MODEL_TRABALHO VARCHAR(30),
  TIPO_CONTRATO VARCHAR(30),
  QUANT_VAGA SMALLINT NOT NULL,
  REMUNERACAO DECIMAL(10,2),
  DESCRICAO_VAGA VARCHAR(4000),
  REQUISITOS VARCHAR(4000),
  ACESSIBILIDADE_OFERECIDA VARCHAR(4000),
  CONSTRAINT PK_VAGA PRIMARY KEY (COD_VAGA),
  CONSTRAINT FK_VAGA_EMPRESA FOREIGN KEY (CNPJ) REFERENCES EMPRESA(CNPJ),
  CONSTRAINT CK_VAGA_QUANT CHECK (QUANT_VAGA > 0)
) ENGINE=InnoDB;

CREATE TABLE CANDIDATO (
  CPF CHAR(11) NOT NULL,
  NOME VARCHAR(150) NOT NULL,
  CNH VARCHAR(20),
  ESTADO_CIVIL VARCHAR(20),
  GENERO VARCHAR(30),
  DATA_NASCIMENTO DATE,
  SENHA VARCHAR(255) NOT NULL,
  EMAIL VARCHAR(150) NOT NULL,
  CONTATO VARCHAR(20),
  CEP CHAR(8),
  NUMERO VARCHAR(10),
  CIDADE VARCHAR(100),
  UF CHAR(2),
  LOGRADOURO VARCHAR(150),
  COMPLEMENTO VARCHAR(100),
  BAIRRO VARCHAR(100),
  CONSTRAINT PK_CANDIDATO PRIMARY KEY (CPF),
  CONSTRAINT UQ_CANDIDATO_EMAIL UNIQUE (EMAIL)
) ENGINE=InnoDB;

CREATE TABLE CID (
  CID VARCHAR(10) NOT NULL,
  DESCRICAO VARCHAR(255) NOT NULL,
  CONSTRAINT PK_CID PRIMARY KEY (CID)
) ENGINE=InnoDB;

CREATE TABLE FORMACAO (
  COD_FORMACAO BIGINT NOT NULL AUTO_INCREMENT,
  ID_CANDIDATO CHAR(11) NOT NULL,
  ESCOLARIDADE VARCHAR(50),
  CURSO VARCHAR(150),
  INSTITUICAO VARCHAR(150),
  DATA_INICIO DATE,
  DATA_CONCLUSAO DATE,
  CONSTRAINT PK_FORMACAO PRIMARY KEY (COD_FORMACAO),
  CONSTRAINT FK_FORMACAO_CANDIDATO FOREIGN KEY (ID_CANDIDATO) REFERENCES CANDIDATO(CPF) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE EXPERIENCIA (
  COD_EXP BIGINT NOT NULL AUTO_INCREMENT,
  ID_CANDIDATO CHAR(11) NOT NULL,
  EMPRESA VARCHAR(150),
  CARGO VARCHAR(100),
  DATA_INICIO DATE,
  DATA_SAIDA DATE,
  CONSTRAINT PK_EXPERIENCIA PRIMARY KEY (COD_EXP),
  CONSTRAINT FK_EXPERIENCIA_CANDIDATO FOREIGN KEY (ID_CANDIDATO) REFERENCES CANDIDATO(CPF) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE HABILIDADES (
  COD_HAB BIGINT NOT NULL AUTO_INCREMENT,
  ID_CANDIDATO CHAR(11) NOT NULL,
  HABILIDADES_TECNICAS VARCHAR(4000),
  HABILIDADES_COMPORTAMENTAIS VARCHAR(4000),
  CONSTRAINT PK_HABILIDADES PRIMARY KEY (COD_HAB),
  CONSTRAINT FK_HABILIDADES_CANDIDATO FOREIGN KEY (ID_CANDIDATO) REFERENCES CANDIDATO(CPF) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ACESSIBILIDADE (
  COD_ACESSIBILIDADE BIGINT NOT NULL AUTO_INCREMENT,
  ID_CANDIDATO CHAR(11) NOT NULL,
  TIPO_DEFICIENCIA VARCHAR(100),
  LAUDO VARCHAR(255),
  FORMA_COMUNICACAO VARCHAR(100),
  NIVEL_APOIO VARCHAR(100),
  ADAPTACAO_ERGONOMICA VARCHAR(4000),
  CONSTRAINT PK_ACESSIBILIDADE PRIMARY KEY (COD_ACESSIBILIDADE),
  CONSTRAINT UQ_ACESSIBILIDADE_CANDIDATO UNIQUE (ID_CANDIDATO),
  CONSTRAINT FK_ACESSIBILIDADE_CANDIDATO FOREIGN KEY (ID_CANDIDATO) REFERENCES CANDIDATO(CPF) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE CANDIDATAR (
  CPF CHAR(11) NOT NULL,
  COD_VAGA BIGINT NOT NULL,
  CONSTRAINT PK_CANDIDATAR PRIMARY KEY (CPF, COD_VAGA),
  CONSTRAINT FK_CANDIDATAR_CANDIDATO FOREIGN KEY (CPF) REFERENCES CANDIDATO(CPF) ON DELETE CASCADE,
  CONSTRAINT FK_CANDIDATAR_VAGA FOREIGN KEY (COD_VAGA) REFERENCES VAGA(COD_VAGA) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE TER (
  COD_ACESSIBILIDADE BIGINT NOT NULL,
  CID VARCHAR(10) NOT NULL,
  CONSTRAINT PK_TER PRIMARY KEY (COD_ACESSIBILIDADE, CID),
  CONSTRAINT FK_TER_ACESSIBILIDADE FOREIGN KEY (COD_ACESSIBILIDADE) REFERENCES ACESSIBILIDADE(COD_ACESSIBILIDADE) ON DELETE CASCADE,
  CONSTRAINT FK_TER_CID FOREIGN KEY (CID) REFERENCES CID(CID) ON DELETE CASCADE
) ENGINE=InnoDB;

