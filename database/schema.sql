CREATE DATABASE IF NOT EXISTS `includedlives_dev`
  DEFAULT CHARACTER SET utf8mb4 
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE `includedlives_dev`;

-- Criação não destrutiva. Nunca execute DROP em produção.

-- 1. TABELA EMPRESA
CREATE TABLE IF NOT EXISTS `EMPRESA` (
    `ID_EMPRESA`       BIGINT AUTO_INCREMENT PRIMARY KEY,
    `CNPJ`             CHAR(14) NOT NULL,
    `NOME_FANTASIA`    VARCHAR(150) NOT NULL,
    `RAZAO_SOCIAL`     VARCHAR(150) NOT NULL,
    `SENHA`            VARCHAR(255) NOT NULL,
    `EMAIL`            VARCHAR(150) NOT NULL,
    `RAMO`             VARCHAR(100) NULL,
    `PORTE`            VARCHAR(30) NULL,
    `RESPONSAVEL`      VARCHAR(150) NULL,
    `CONTATO`          VARCHAR(20) NULL,
    `CEP`              CHAR(8) NULL,
    `LOGRADOURO`       VARCHAR(150) NULL,
    `NUMERO`           VARCHAR(10) NULL,
    `CIDADE`           VARCHAR(100) NULL,
    `UF`               CHAR(2) NULL,
    `COMPLEMENTO`      VARCHAR(100) NULL,
    `BAIRRO`           VARCHAR(100) NULL,
    `SITE_URL` VARCHAR(255) NULL,
    `INSTAGRAM_URL` VARCHAR(255) NULL,
    `LINKEDIN_URL` VARCHAR(255) NULL,
    `LOGO_URL` VARCHAR(500) NULL,
    CONSTRAINT `UQ_EMPRESA_CNPJ` UNIQUE (`CNPJ`),
    CONSTRAINT `UQ_EMPRESA_EMAIL` UNIQUE (`EMAIL`)
) ENGINE=InnoDB;

-- 2. TABELA CANDIDATO
CREATE TABLE IF NOT EXISTS `CANDIDATO` (
    `ID_CANDIDATO`     BIGINT AUTO_INCREMENT PRIMARY KEY,
    `CPF`              CHAR(11) NOT NULL,
    `NOME`             VARCHAR(150) NOT NULL,
    `CNH`              VARCHAR(20) NULL,
    `ESTADO_CIVIL`     VARCHAR(20) NULL,
    `GENERO`           VARCHAR(30) NULL,
    `DATA_NASCIMENTO`  DATE NOT NULL,
    `SENHA`            VARCHAR(255) NOT NULL,
    `EMAIL`            VARCHAR(150) NOT NULL,
    `CONTATO`          VARCHAR(20) NULL,
    `CEP`              CHAR(8) NULL,
    `LOGRADOURO`       VARCHAR(150) NULL,
    `NUMERO`           VARCHAR(10) NULL,
    `CIDADE`           VARCHAR(100) NULL,
    `UF`               CHAR(2) NULL,
    `COMPLEMENTO`      VARCHAR(100) NULL,
    `BAIRRO`           VARCHAR(100) NULL,
    `SOBRE_MIM`        TEXT NULL,
    `DISPONIVEL_BANCO` CHAR(1) NOT NULL DEFAULT 'S',
    CONSTRAINT `UQ_CANDIDATO_CPF` UNIQUE (`CPF`),
    CONSTRAINT `UQ_CANDIDATO_EMAIL` UNIQUE (`EMAIL`),
    CONSTRAINT `CK_CANDIDATO_DISP` CHECK (`DISPONIVEL_BANCO` IN ('S', 'N'))
) ENGINE=InnoDB;

-- 3. TABELA VAGA
CREATE TABLE IF NOT EXISTS `VAGA` (
    `COD_VAGA`                 BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ID_EMPRESA`               BIGINT NOT NULL,
    `NOME_VAGA`                VARCHAR(150) NOT NULL,
    `STATUS`                   VARCHAR(10) NOT NULL DEFAULT 'PAUSADA',
    `CIDADE`                   VARCHAR(100) NULL,
    `UF`                       CHAR(2) NULL,
    `AREA_PROFISSIONAL`        VARCHAR(100) NULL,
    `MODELO_TRABALHO`          VARCHAR(30) NULL,
    `TIPO_CONTRATO`            VARCHAR(30) NULL,
    `QUANT_VAGA`               INT NOT NULL,
    `REMUNERACAO`              DECIMAL(10, 2) NULL,
    `DESCRICAO_VAGA`           TEXT NULL,
    `REQUISITOS`               TEXT NULL,
    `BENEFICIOS`               TEXT NULL,
    `OUTROS_DIFERENCIAIS`      TEXT NULL,
    `ACESSIBILIDADE_OFERECIDA` TEXT NULL,
    CONSTRAINT `FK_VAGA_EMPRESA` FOREIGN KEY (`ID_EMPRESA`) 
        REFERENCES `EMPRESA` (`ID_EMPRESA`) ON DELETE CASCADE,
    CONSTRAINT `CK_VAGA_QUANT` CHECK (`QUANT_VAGA` > 0),
    CONSTRAINT `CK_VAGA_STATUS` CHECK (`STATUS` IN ('ATIVA', 'PAUSADA', 'ENCERRADA'))
) ENGINE=InnoDB;

-- 4. TABELA CID
CREATE TABLE IF NOT EXISTS `CID` (
    `CID`       VARCHAR(10) NOT NULL PRIMARY KEY,
    `DESCRICAO` VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

-- 5. TABELA FORMACAO
CREATE TABLE IF NOT EXISTS `FORMACAO` (
    `COD_FORMACAO`   BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ID_CANDIDATO`   BIGINT NOT NULL,
    `ESCOLARIDADE`   VARCHAR(50) NULL,
    `CURSO`          VARCHAR(150) NULL,
    `INSTITUICAO`    VARCHAR(150) NULL,
    `DATA_INICIO`    DATE NULL,
    `DATA_CONCLUSAO` DATE NULL,
    CONSTRAINT `FK_FORMACAO_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 6. TABELA EXPERIENCIA
CREATE TABLE IF NOT EXISTS `EXPERIENCIA` (
    `COD_EXP`              BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ID_CANDIDATO`         BIGINT NOT NULL,
    `EMPRESA`              VARCHAR(150) NULL,
    `CARGO`                VARCHAR(100) NULL,
    `DATA_INICIO`          DATE NULL,
    `DATA_SAIDA`           DATE NULL,
    `DESCRICAO_ATIVIDADES` TEXT NULL,
    CONSTRAINT `FK_EXPERIENCIA_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 7. TABELA HABILIDADES
CREATE TABLE IF NOT EXISTS `HABILIDADES` (
    `COD_HAB`         BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ID_CANDIDATO`    BIGINT NOT NULL,
    `NOME_HABILIDADE` VARCHAR(100) NOT NULL,
    `TIPO_HABILIDADE` VARCHAR(30) NOT NULL DEFAULT 'TECNICA',
    CONSTRAINT `FK_HABILIDADES_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE,
    CONSTRAINT `CK_TIPO_HABILIDADE` CHECK (`TIPO_HABILIDADE` IN ('TECNICA', 'COMPORTAMENTAL'))
) ENGINE=InnoDB;

-- 8. TABELA ACESSIBILIDADE
CREATE TABLE IF NOT EXISTS `ACESSIBILIDADE` (
    `COD_ACESSIBILIDADE`   BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ID_CANDIDATO`         BIGINT NOT NULL,
    `TIPO_DEFICIENCIA`     VARCHAR(100) NULL,
    `LAUDO`                VARCHAR(255) NULL,
    `FORMA_COMUNICACAO`    VARCHAR(100) NULL,
    `NIVEL_APOIO`          VARCHAR(100) NULL,
    `ADAPTACAO_ERGONOMICA` TEXT NULL,
    CONSTRAINT `UQ_ACESSIBILIDADE_CANDIDATO` UNIQUE (`ID_CANDIDATO`),
    CONSTRAINT `FK_ACESSIBILIDADE_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 9. TABELA CANDIDATAR
CREATE TABLE IF NOT EXISTS `CANDIDATAR` (
    `ID_CANDIDATO`       BIGINT NOT NULL,
    `COD_VAGA`           BIGINT NOT NULL,
    `DATA_CANDIDATURA`   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `STATUS_CANDIDATURA` VARCHAR(30) NOT NULL DEFAULT 'INSCRITO',
    PRIMARY KEY (`ID_CANDIDATO`, `COD_VAGA`),
    CONSTRAINT `FK_CANDIDATAR_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE,
    CONSTRAINT `FK_CANDIDATAR_VAGA` FOREIGN KEY (`COD_VAGA`)
        REFERENCES `VAGA` (`COD_VAGA`) ON DELETE CASCADE,
    CONSTRAINT `CK_CANDIDATAR_STATUS` 
        CHECK (`STATUS_CANDIDATURA` IN ('INSCRITO', 'EM_ANALISE', 'ENTREVISTA', 'FINALIZADO', 'APROVADO', 'REPROVADO'))
) ENGINE=InnoDB;

-- 10. TABELA TER
CREATE TABLE IF NOT EXISTS `TER` (
    `COD_ACESSIBILIDADE` BIGINT NOT NULL,
    `CID`                VARCHAR(10) NOT NULL,
    PRIMARY KEY (`COD_ACESSIBILIDADE`, `CID`),
    CONSTRAINT `FK_TER_ACESSIBILIDADE` FOREIGN KEY (`COD_ACESSIBILIDADE`)
        REFERENCES `ACESSIBILIDADE` (`COD_ACESSIBILIDADE`) ON DELETE CASCADE,
    CONSTRAINT `FK_TER_CID` FOREIGN KEY (`CID`)
        REFERENCES `CID` (`CID`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 11. TABELA VAGA_SALVA
CREATE TABLE IF NOT EXISTS `VAGA_SALVA` (
    `ID_CANDIDATO`    BIGINT NOT NULL,
    `COD_VAGA`        BIGINT NOT NULL,
    `DATA_SALVAMENTO` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`ID_CANDIDATO`, `COD_VAGA`),
    CONSTRAINT `FK_SALVA_CANDIDATO` FOREIGN KEY (`ID_CANDIDATO`)
        REFERENCES `CANDIDATO` (`ID_CANDIDATO`) ON DELETE CASCADE,
    CONSTRAINT `FK_SALVA_VAGA` FOREIGN KEY (`COD_VAGA`)
        REFERENCES `VAGA` (`COD_VAGA`) ON DELETE CASCADE
) ENGINE=InnoDB;

