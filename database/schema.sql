CREATE TABLE IF NOT EXISTS CONVERSA (
 ID_CONVERSA BIGINT AUTO_INCREMENT PRIMARY KEY,
 ID_EMPRESA BIGINT NOT NULL,
 ID_CANDIDATO BIGINT NOT NULL,
 COD_VAGA BIGINT NOT NULL,
 CRIADA_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY UQ_CONVERSA_PARTICIPANTES_VAGA (ID_EMPRESA,ID_CANDIDATO,COD_VAGA),
 FOREIGN KEY (ID_EMPRESA) REFERENCES EMPRESA(ID_EMPRESA) ON DELETE CASCADE,
 FOREIGN KEY (ID_CANDIDATO) REFERENCES CANDIDATO(ID_CANDIDATO) ON DELETE CASCADE,
 FOREIGN KEY (COD_VAGA) REFERENCES VAGA(COD_VAGA) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS MENSAGEM (
 ID_MENSAGEM BIGINT AUTO_INCREMENT PRIMARY KEY,
 ID_CONVERSA BIGINT NOT NULL,
 REMETENTE_TIPO VARCHAR(10) NOT NULL,
 TEXTO VARCHAR(2000) NOT NULL,
 ENVIADA_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 LIDA_EM DATETIME NULL,
 CONSTRAINT CK_MENSAGEM_REMETENTE CHECK (REMETENTE_TIPO IN ('empresa','candidato')),
 FOREIGN KEY (ID_CONVERSA) REFERENCES CONVERSA(ID_CONVERSA) ON DELETE CASCADE,
 INDEX IDX_MENSAGEM_CONVERSA (ID_CONVERSA,ID_MENSAGEM)
) ENGINE=InnoDB;
