USE includedlives_dev;
-- Execute depois de migracao_mensagens.sql. Preserva contas, vagas e candidaturas.
DELIMITER $$
DROP PROCEDURE IF EXISTS included_add_company_columns$$
CREATE PROCEDURE included_add_company_columns()
BEGIN
 IF NOT EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESA' AND COLUMN_NAME='SITE_URL') THEN ALTER TABLE EMPRESA ADD SITE_URL VARCHAR(255) NULL; END IF;
 IF NOT EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESA' AND COLUMN_NAME='INSTAGRAM_URL') THEN ALTER TABLE EMPRESA ADD INSTAGRAM_URL VARCHAR(255) NULL; END IF;
 IF NOT EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESA' AND COLUMN_NAME='LINKEDIN_URL') THEN ALTER TABLE EMPRESA ADD LINKEDIN_URL VARCHAR(255) NULL; END IF;
 IF NOT EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESA' AND COLUMN_NAME='LOGO_URL') THEN ALTER TABLE EMPRESA ADD LOGO_URL VARCHAR(500) NULL; END IF;
 IF EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE() AND TABLE_NAME='CANDIDATAR' AND CONSTRAINT_NAME='CK_CANDIDATAR_STATUS') THEN
  ALTER TABLE CANDIDATAR DROP CHECK CK_CANDIDATAR_STATUS;
 END IF;
 ALTER TABLE CANDIDATAR ADD CONSTRAINT CK_CANDIDATAR_STATUS CHECK (STATUS_CANDIDATURA IN ('INSCRITO','EM_ANALISE','ENTREVISTA','FINALIZADO','APROVADO','REPROVADO'));
END$$
CALL included_add_company_columns()$$
DROP PROCEDURE included_add_company_columns$$
DELIMITER ;
